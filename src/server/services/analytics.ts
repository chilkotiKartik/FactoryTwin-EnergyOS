export interface RangeSummary {
  fromDay: string;
  toDay: string;
  window: { from: number; to: number };
  energyKwh: number;
  tonnesPoured: number;
  heatsCount: number;
  heatsTapped: number;
  sec: number | null;
  costPaise: number;
  costPerTonnePaise: number | null;
  unpricedKwh: number;
  costByKind: Record<string, { kwh: number; paise: number }>;
  holdingMinutes: number;
  holdingKwh: number;
  linkedKwh: number;
  unlinkedKwh: number;
  unlinkedSpans: { from: number; to: number; kwh: number; peakKw: number }[];
  readingCount: number;
  invalidReadings: number;
  suspectReadings: number;
  completenessDay: number | null;
  completenessOperating: number | null;
  gaps: { from: number; to: number; missingIntervals: number }[];
  emissionsKg: number | null;
  evidence: string;
  heats: HeatRow[];
  openAnomalies: number;
  pendingApprovals: number;
  lastReadingAt: number | null;
}

export async function rangeSummary(db: DB, actor: Actor, fromDay: string, toDay: string): Promise<RangeSummary> {
  requirePerm(actor, "view");
  const f = actor.factory;
  const tz = f.timeZone;
  const from = localDayStart(fromDay, tz);
  const to = localDayStart(addDays(toDay, 1), tz);
  const [readings, heatRows, versions, meter, pending] = await Promise.all([
    readingsBetween(db, f.id, from, to),
    db
      .select()
      .from(heats)
      .where(and(eq(heats.factoryId, f.id), gte(heats.dayDate, fromDay), lte(heats.dayDate, toDay)))
      .orderBy(asc(heats.startAt)),
    loadTariffVersions(db, f.id),
    primaryMeter(db, f.id),
    db
      .select({ c: sql<number>`count(*)` })
      .from(recommendations)
      .where(and(eq(recommendations.factoryId, f.id), eq(recommendations.status, "PENDING"))),
  ]);
  const intervalSeconds = meter?.intervalSeconds ?? 60;
  const valid = readings.filter((r) => r.quality !== "INVALID");
  const energyKwh = valid.reduce((s, r) => s + r.energyKwh, 0);
  const cost = energyCost(valid, versions);
  const heatIds = heatRows.map((h) => h.id);
  const anomalyRows = heatIds.length
    ? await db.select().from(anomalies).where(and(eq(anomalies.factoryId, f.id), inArray(anomalies.heatId, heatIds)))
    : [];
  const anomalyByHeat = new Map(anomalyRows.map((a) => [a.heatId, a]));

  const tapped = heatRows.filter((h) => h.tapAt !== null);
  const tonnesPoured = tapped.reduce((s, h) => s + (h.pouredKg ?? 0), 0) / 1000;
  const link = linkReadingsToHeats(
    valid,
    tapped.map((h) => ({ id: h.id, start: h.startAt, end: h.tapAt! })),
    intervalSeconds,
  );
  const opStart = heatRows.length ? heatRows[0].startAt : null;
  const opEnd = tapped.length ? Math.max(...tapped.map((h) => h.tapAt!)) : null;
  const readingTs = readings.map((r) => r.ts);
  const opCount = opStart !== null && opEnd !== null ? readings.filter((r) => r.ts >= opStart && r.ts < opEnd).length : 0;
  const gaps = opStart !== null && opEnd !== null ? findGaps(readingTs, opStart, opEnd, intervalSeconds) : [];

  const provs = new Set<Provenance>();
  for (const r of readings) provs.add(r.provenance as Provenance);
  for (const h of heatRows) provs.add(h.provenance as Provenance);

  const heatOut: HeatRow[] = heatRows.map((h) => {
    const a = anomalyByHeat.get(h.id);
    const kwh = h.meterKwh ?? h.manualKwh;
    const variance = kwh !== null && h.expectedKwh !== null ? kwh - h.expectedKwh : null;
    return {
      id: h.id,
      heatNo: h.heatNo,
      dayDate: h.dayDate,
      startAt: h.startAt,
      tapAt: h.tapAt,
      chargeKg: h.chargeKg,
      pouredKg: h.pouredKg,
      meterKwh: kwh,
      expectedKwh: h.expectedKwh,
      varianceKwh: variance,
      variancePct: variance !== null && h.expectedKwh ? (100 * variance) / h.expectedKwh : null,
      secKwhPerT: specificEnergy(kwh, h.pouredKg !== null ? h.pouredKg / 1000 : null),
      holdingMinutes: h.holdingMinutes,
      holdingKwh: h.holdingKwh,
      dataQuality: h.dataQuality,
      provenance: h.provenance,
      anomalySeverity: a?.severity ?? null,
      anomalyId: a && a.severity ? a.id : null,
      mouldSet: h.mouldSet,
    };
  });

  return {
    fromDay,
    toDay,
    window: { from, to },
    energyKwh,
    tonnesPoured,
    heatsCount: heatRows.length,
    heatsTapped: tapped.length,
    sec: specificEnergy(energyKwh, tonnesPoured),
    costPaise: cost.totalPaise,
    costPerTonnePaise: costPerTonne(cost.totalPaise, tonnesPoured),
    unpricedKwh: cost.unpricedKwh,
    costByKind: cost.byKind,
    holdingMinutes: heatRows.reduce((s, h) => s + (h.holdingMinutes ?? 0), 0),
    holdingKwh: heatRows.reduce((s, h) => s + (h.holdingKwh ?? 0), 0),
    linkedKwh: link.linkedKwh,
    unlinkedKwh: link.unlinkedKwh,
    unlinkedSpans: link.unlinkedSpans,
    readingCount: readings.length,
    invalidReadings: readings.length - valid.length,
    suspectReadings: readings.filter((r) => r.quality === "SUSPECT").length,
    completenessDay: completeness(readings.length, from, Math.min(to, Math.max(from, Date.now())), intervalSeconds),
    completenessOperating: opStart !== null && opEnd !== null ? completeness(opCount, opStart, opEnd, intervalSeconds) : null,
    gaps,
    emissionsKg: emissionsKg(energyKwh, f.emissionFactor),
    evidence: combineProvenance(provs),
    heats: heatOut,
    openAnomalies: anomalyRows.filter((a) => a.severity !== null && a.status === "OPEN").length,
    pendingApprovals: Number(pending[0]?.c ?? 0),
    lastReadingAt: readings.length ? readings[readings.length - 1].ts : null,
  };
}

export interface DailyPoint {
  day: string;
  energyKwh: number;
  tonnes: number;
  sec: number | null;
  holdingMinutes: number;
}

/** Per-day energy and tonnes for a trend chart (aggregated in SQL). */
export async function dailySeries(db: DB, actor: Actor, fromDay: string, toDay: string): Promise<DailyPoint[]> {
  requirePerm(actor, "view");
  const f = actor.factory;
  const from = localDayStart(fromDay, f.timeZone);
  const to = localDayStart(addDays(toDay, 1), f.timeZone);
  const offset = zoneOffsetMs(from, f.timeZone);
  const energy = await db
    .select({
      dayIdx: sql<number>`cast((${meterReadings.ts} + ${offset}) / 86400000 as integer)`,
      kwh: sql<number>`sum(${meterReadings.energyKwh})`,
    })
    .from(meterReadings)
    .where(and(eq(meterReadings.factoryId, f.id), gte(meterReadings.ts, from), sql`${meterReadings.ts} < ${to}`, sql`${meterReadings.quality} != 'INVALID'`))
    .groupBy(sql`1`);
  const prod = await db
    .select({ day: heats.dayDate, kg: sql<number>`sum(coalesce(${heats.pouredKg}, 0))`, hold: sql<number>`sum(coalesce(${heats.holdingMinutes}, 0))` })
    .from(heats)
    .where(and(eq(heats.factoryId, f.id), gte(heats.dayDate, fromDay), lte(heats.dayDate, toDay)))
    .groupBy(heats.dayDate);
  const byDay = new Map<string, DailyPoint>();
  for (const e of energy) {
    const day = new Date(e.dayIdx * 86400000).toISOString().slice(0, 10);
    byDay.set(day, { day, energyKwh: e.kwh, tonnes: 0, sec: null, holdingMinutes: 0 });
  }
  for (const p of prod) {
    const cur = byDay.get(p.day) ?? { day: p.day, energyKwh: 0, tonnes: 0, sec: null, holdingMinutes: 0 };
    cur.tonnes = p.kg / 1000;
    cur.holdingMinutes = p.hold;
    byDay.set(p.day, cur);
  }
  return [...byDay.values()]
    .map((d) => ({ ...d, sec: specificEnergy(d.energyKwh, d.tonnes) }))
    .sort((a, b) => a.day.localeCompare(b.day));
}

export interface TraceData {
  day: string;
  dayStart: number;
  points: { m: number; kw: number | null }[];
  heats: { id: string; heatNo: string; startMin: number; meltEndMin: number | null; tapMin: number | null; holdingMinutes: number | null; flagged: boolean; mouldSet: number | null; mouldReadyMin: number | null }[];
  tariffBands: { startMin: number; endMin: number; kind: string; label: string; ratePaise: number }[];
  normalRatePaise: number | null;
}

/** Minute-level trace for a day, with heat windows and tariff bands, in local minutes. */
export async function dayTrace(db: DB, actor: Actor, day: string): Promise<TraceData> {
  requirePerm(actor, "view");
  const f = actor.factory;
  const start = localDayStart(day, f.timeZone);
  const end = localDayStart(addDays(day, 1), f.timeZone);
  const [readings, heatRows, versions] = await Promise.all([
    readingsBetween(db, f.id, start, end),
    db.select().from(heats).where(and(eq(heats.factoryId, f.id), eq(heats.dayDate, day))).orderBy(asc(heats.startAt)),
    loadTariffVersions(db, f.id),
  ]);
  const flagged = heatRows.length
    ? await db
        .select({ heatId: anomalies.heatId, severity: anomalies.severity })
        .from(anomalies)
        .where(inArray(anomalies.heatId, heatRows.map((h) => h.id)))
    : [];
  const flaggedSet = new Set(flagged.filter((a) => a.severity).map((a) => a.heatId));
  const toMin = (ts: number | null) => (ts === null ? null : Math.round((ts - start) / 60000));
  const byMinute = new Array<number | null>(1440).fill(null);
  for (const r of readings) {
    const m = Math.floor((r.ts - start) / 60000);
    if (m >= 0 && m < 1440 && r.quality !== "INVALID") byMinute[m] = r.powerKw;
  }
  const { bands, normalRatePaise } = bandsFor(versions, start);
  return {
    day,
    dayStart: start,
    points: byMinute.map((kw, m) => ({ m, kw })),
    heats: heatRows.map((h) => ({
      id: h.id,
      heatNo: h.heatNo,
      startMin: toMin(h.startAt)!,
      meltEndMin: toMin(h.meltEndAt),
      tapMin: toMin(h.tapAt),
      holdingMinutes: h.holdingMinutes,
      flagged: flaggedSet.has(h.id),
      mouldSet: h.mouldSet,
      mouldReadyMin: toMin(h.mouldReadyAt),
    })),
    tariffBands: bands,
    normalRatePaise,
  };
}

type Band = TraceData["tariffBands"][number];

function bandsFor(versions: Awaited<ReturnType<typeof loadTariffVersions>>, dayStart: number): { bands: Band[]; normalRatePaise: number | null } {
  const v = versionAt(versions, dayStart + 12 * 3600_000);
  const bands: Band[] = [];
  if (!v) return { bands, normalRatePaise: null };
  let cur = rateAtMinute(v, 0);
  let s = 0;
  for (let m = 1; m <= 1440; m++) {
    const r = m < 1440 ? rateAtMinute(v, m) : null;
    if (!r || r.ratePaise !== cur.ratePaise || r.kind !== cur.kind) {
      bands.push({ startMin: s, endMin: m, kind: cur.kind, label: cur.label, ratePaise: cur.ratePaise });
      if (r) {
        cur = r;
        s = m;
      }
    }
  }
  return { bands, normalRatePaise: v.normalRatePaise };
}

/** Tariff windows in force on a local day (by the version effective at noon). */
export async function tariffBands(db: DB, actor: Actor, day: string): Promise<{ bands: Band[]; normalRatePaise: number | null }> {
  requirePerm(actor, "view");
  const versions = await loadTariffVersions(db, actor.factory.id);
  return bandsFor(versions, localDayStart(day, actor.factory.timeZone));
}
