export type DataMode = "SIMULATION" | "LIVE" | "OFFLINE";

export async function dataMode(db: DB, actor: Actor): Promise<{ mode: DataMode; lastReadingAt: number | null; detail: string }> {
  const last = await db
    .select({ ts: meterReadings.ts, provenance: meterReadings.provenance })
    .from(meterReadings)
    .where(eq(meterReadings.factoryId, actor.factory.id))
    .orderBy(desc(meterReadings.ts))
    .limit(1);
  const lastTs = last[0]?.ts ?? null;
  if (actor.factory.isSimulation) {
    return { mode: "SIMULATION", lastReadingAt: lastTs, detail: "Synthetic data generated by the scenario engine. Not field validation." };
  }
  const meter = await primaryMeter(db, actor.factory.id);
  const f = freshness(lastTs, Date.now(), meter?.intervalSeconds ?? 60);
  // LIVE only when genuine measured readings arrived recently through the ingest API.
  if (f.status === "FRESH" && last[0]?.provenance === "MEASURED") {
    return { mode: "LIVE", lastReadingAt: lastTs, detail: "Measured readings received within the last five intervals." };
  }
  return {
    mode: "OFFLINE",
    lastReadingAt: lastTs,
    detail: lastTs === null ? "No meter readings yet. Import a CSV or connect a meter." : "No fresh measured readings. Figures use stored data only.",
  };
}

export async function availableDays(db: DB, actor: Actor): Promise<string[]> {
  const rows = await db
    .selectDistinct({ d: heats.dayDate })
    .from(heats)
    .where(eq(heats.factoryId, actor.factory.id))
    .orderBy(desc(heats.dayDate));
  return rows.map((r) => r.d);
}

