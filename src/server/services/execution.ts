/**
 * Record a SIMULATED outcome for a plan: the simulator executes the plan's
 * active schedule (approved recommendation, or current practice after a
 * rejection) and stores the resulting heats and meter readings. Only possible in
 * a simulation factory; a real factory's outcome comes from its meter data.
 */
export async function recordSimulatedOutcome(db: DB, actor: Actor, planId: string) {
  requirePerm(actor, "outcome.record");
  const f = actor.factory;
  if (!f.isSimulation) throw forbidden("Simulated outcomes can only be recorded in a simulation factory. Real outcomes come from meter data.");
  const detail = await getPlan(db, actor, planId);
  if (!detail) throw notFound("Plan");
  const active = await activeSchedule(db, actor, planId);
  if (!active) throw validation("This plan has no schedule yet. Run the optimiser first.");
  const pending = await db.query.recommendations.findFirst({
    where: and(eq(s.recommendations.planId, planId), eq(s.recommendations.status, "PENDING")),
  });
  if (pending) throw conflict("A recommendation is still awaiting a decision. Approve or reject it first.");
  const existing = await db.query.heats.findFirst({ where: and(eq(s.heats.factoryId, f.id), eq(s.heats.dayDate, detail.plan.planDate)) });
  if (existing) throw conflict(`Heats already exist for ${detail.plan.planDate}. Reset the scenario to record a new outcome.`);
  const furnace = await db.query.furnaces.findFirst({ where: eq(s.furnaces.factoryId, f.id) });
  const meter = await db.query.meters.findFirst({ where: eq(s.meters.factoryId, f.id) });
  if (!furnace || !meter) throw validation("Missing furnace or meter.");
  const params = simParamsFor(f, furnace);
  const rec = await db.query.recommendations.findFirst({
    where: and(eq(s.recommendations.planId, planId), eq(s.recommendations.proposedScheduleId, active.version.id)),
  });
  const plan = detail.heats.map((h) => ({
    heatNo: h.heatNo,
    chargeKg: h.chargeKg,
    pouredKg: h.pouredKg,
    mouldSet: h.mouldSet ?? 0,
    mouldReadyMin: h.mouldReadyMin ?? 0,
    orderCode: h.orderCode,
  }));
  const day = simulateDay(
    detail.plan.planDate,
    plan,
    { kind: "FIXED_STARTS", startsMin: active.items.map((i) => i.startMin) },
    params,
    BASE_SEED + 2 + (hashSeed(active.version.kind) % 1000),
  );
  const grades = new Map(detail.orders.map((o) => [o.code, o.grade]));
  const execId = newId("exe");
  const summary = {
    scheduleKind: active.version.kind,
    heats: day.heats.length,
    tonnes: day.heats.reduce((a, h) => a + h.pouredKg, 0) / 1000,
    kwh: day.readings.reduce((a, r) => a + r.energyKwh, 0),
    holdMinutes: day.heats.reduce((a, h) => a + h.holdMin, 0),
    note: "SIMULATED outcome generated by the scenario engine. Not a field result.",
  };
  await db.transaction(async (tx) => {
    await tx.insert(s.executionRecords).values({
      id: execId,
      factoryId: f.id,
      planId,
      scheduleVersionId: active.version.id,
      recommendationId: rec?.id ?? null,
      dayDate: detail.plan.planDate,
      kind: "SIMULATED_OUTCOME",
      provenance: "SIMULATED",
      summary,
      createdBy: actor.userId,
    });
    await writeSimDay(tx, { factoryId: f.id, furnaceId: furnace.id, meterId: meter.id, timeZone: f.timeZone }, day, grades, { executionId: execId });
    await audit(tx, actor, "outcome.record_simulated", "execution_record", execId, { planId, day: detail.plan.planDate, ...summary });
  });
  await analyseFactory(db, actor, "outcome.record");
  return { executionId: execId, day: detail.plan.planDate };
}

export async function listExecutions(db: DB, actor: Actor) {
  requirePerm(actor, "view");
  return db.select().from(s.executionRecords).where(eq(s.executionRecords.factoryId, actor.factory.id)).orderBy(desc(s.executionRecords.createdAt));
}

export function dayBounds(day: string, tz: string) {
  return { from: localDayStart(day, tz), to: localDayStart(addDays(day, 1), tz) };
}
